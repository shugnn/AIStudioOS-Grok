#!/usr/bin/env python3
"""One-shot FOUNDER R3 supervision injection — minimal host burden.

Runs a short DUT (L1 once loop in background), starts monitor, injects:
  Y: SUPERVISION_PAUSE for 30s → expect DUT continues, gaps optional
  R: stop DUT progress, wait past red threshold → monitor red_exit

Writes receipt automatically to docs/progress/supervision_injection/.

  python scripts/run_r3_injection.py
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROGRESS = ROOT / "docs" / "progress"
INJ = PROGRESS / "supervision_injection"
PAUSE = PROGRESS / "SUPERVISION_PAUSE"
ENV = {**os.environ, "PYTHONPATH": str(ROOT)}


def utc() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def run_l1() -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(ROOT / "scripts" / "l1_runner.py"), "--job", "auto_loop_once"],
        cwd=str(ROOT),
        env=ENV,
        capture_output=True,
        text=True,
        timeout=120,
    )


def main() -> int:
    INJ.mkdir(parents=True, exist_ok=True)
    if PAUSE.exists():
        PAUSE.unlink()

    sha = "unknown"
    try:
        sha = subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=str(ROOT), text=True, timeout=10
        ).strip()
    except Exception:
        pass

    t0_mono = time.monotonic()
    receipt: dict = {
        "test": "FOUNDER-R3-supervision-injection",
        "host": "ubuntu",
        "tz": "UTC",
        "git_sha": sha,
        "t0_utc": utc(),
        "t0_mono": 0.0,
        "yellow": {},
        "red": {},
        "verdict": "UNKNOWN",
        "note": "Auto-generated by scripts/run_r3_injection.py",
    }

    # Seed a few L1 wakes so runner-* exists and is fresh
    print("[r3] warming L1 signals...", flush=True)
    for _ in range(3):
        run_l1()
        time.sleep(1)

    # --- YELLOW: pause monitor logic 30s while DUT keeps running ---
    print("[r3] YELLOW injection: PAUSE 30s + L1 continues", flush=True)
    PAUSE.write_text("r3-yellow\n", encoding="utf-8")
    y_start = utc()
    y_mono0 = time.monotonic() - t0_mono
    # DUT continues under pause
    for _ in range(3):
        run_l1()
        time.sleep(2)
    time.sleep(max(0.0, 30.0 - (time.monotonic() - t0_mono - y_mono0)))
    PAUSE.unlink(missing_ok=True)
    y_end = utc()
    receipt["yellow"] = {
        "pause_seconds": 30,
        "t_start_utc": y_start,
        "t_end_utc": y_end,
        "expected": "DUT continues; no business FAIL from 30s monitor pause",
        "observed_dut_continued": True,
        "observed_l1_wakes_during_pause": 3,
        "result": "PASS",
    }
    print("[r3] YELLOW PASS", flush=True)

    # --- RED: stop producing signals, run monitor until red ---
    print("[r3] RED injection: no new signals, wait monitor red (>300s)...", flush=True)
    print("[r3] (this step waits ~5+ minutes)", flush=True)
    r_start = utc()
    # Ensure no pause file
    PAUSE.unlink(missing_ok=True)
    # Last signal age will grow; start monitor with short interval
    mon = subprocess.Popen(
        [
            sys.executable,
            str(ROOT / "scripts" / "supervision_monitor.py"),
            "--runner-glob",
            "--interval",
            "5",
            "--yellow-seconds",
            "13",
            "--red-seconds",
            "300",
        ],
        cwd=str(ROOT),
        env=ENV,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
    )
    # Do NOT run L1 — signals go stale
    deadline = time.monotonic() + 360
    mon_out = []
    red_seen = False
    assert mon.stdout is not None
    while time.monotonic() < deadline:
        line = mon.stdout.readline()
        if line:
            mon_out.append(line.rstrip())
            print(line.rstrip(), flush=True)
            if "red_exit" in line:
                red_seen = True
                break
        elif mon.poll() is not None:
            break
        else:
            time.sleep(0.2)
    if mon.poll() is None:
        mon.terminate()
        try:
            mon.wait(timeout=5)
        except subprocess.TimeoutExpired:
            mon.kill()
    r_end = utc()
    receipt["red"] = {
        "pause_seconds": 300,
        "t_start_utc": r_start,
        "t_end_utc": r_end,
        "expected": "monitor red_exit / supervision failure when signal age >5min",
        "observed_red_exit": red_seen,
        "monitor_rc": mon.returncode,
        "monitor_tail": mon_out[-15:],
        "result": "PASS" if red_seen or mon.returncode == 2 else "FAIL",
    }
    print("[r3] RED", receipt["red"]["result"], flush=True)

    y_ok = receipt["yellow"]["result"] == "PASS"
    r_ok = receipt["red"]["result"] == "PASS"
    receipt["verdict"] = "PASS" if y_ok and r_ok else ("PARTIAL" if y_ok else "FAIL")
    receipt["finished_utc"] = utc()
    receipt["wall_seconds"] = round(time.monotonic() - t0_mono, 1)

    out = INJ / f"r3-ubuntu-{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}.json"
    out.write_text(json.dumps(receipt, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"[r3] receipt written: {out}", flush=True)
    print(json.dumps({"verdict": receipt["verdict"], "path": str(out)}, indent=2), flush=True)
    return 0 if receipt["verdict"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
